class PostModel {

  final int id;
  final String titulo;
  final String autor;
  final String categoria;
  final String descripcion;
  final String contenido;
  final String imagen;
  final String fecha;

  PostModel({
    required this.id,
    required this.titulo,
    required this.autor,
    required this.categoria,
    required this.descripcion,
    required this.contenido,
    required this.imagen,
    required this.fecha,
  });

}